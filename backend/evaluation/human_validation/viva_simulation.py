from typing import List, Dict, Any, Optional, Tuple
from pydantic import BaseModel, Field
from enum import Enum
from datetime import datetime
import random


class StudentResponseType(str, Enum):
    """Types of student responses to simulate"""
    CORRECT = "correct"  # Knows implementation and can explain reasoning
    TEXTBOOK = "textbook"  # Can recite generic concepts but not codebase-specific
    PARTIAL = "partial"  # Correct answer but missing important context
    CONTRADICTORY = "contradictory"  # Says conflicting things
    MISUNDERSTANDING = "misunderstanding"  # Wrong assumptions about code
    WEAK_EXPLANATION = "weak_explanation"  # Right answer, unclear reasoning


class FollowUpQuestionQuality(str, Enum):
    """Quality of ORACLE follow-up questions"""
    GENERIC = "generic"  # Could apply to any codebase
    PROBING = "probing"  # Tests understanding of specific weakness
    IRRELEVANT = "irrelevant"  # Doesn't relate to previous answer
    CLARIFYING = "clarifying"  # Good clarification question
    DEEPENING = "deepening"  # Pushes understanding deeper
    CONTRADICTING = "contradicting"  # Points out inconsistency


class SimulatedStudentResponse(BaseModel):
    """Response from simulated student to a viva question"""
    question: str
    response_type: StudentResponseType
    response_text: str
    
    # Metadata about the response
    reveals_weakness: Optional[str] = None  # What does this response reveal?
    contains_contradiction: bool = False
    assumes_wrong_context: Optional[str] = None
    misses_important_point: Optional[str] = None
    confidence_expressed: float = Field(ge=0, le=1.0)  # How confident did they sound?


class VivaFollowUpQuestion(BaseModel):
    """Follow-up question generated by ORACLE"""
    previous_question: str
    follow_up_question: str
    oracle_confidence: float
    
    # Evaluation
    quality_assessment: Optional[FollowUpQuestionQuality] = None
    probes_weakness: bool = False  # Does this target the revealed weakness?
    is_generic: bool = False  # Could apply to any language/framework?
    is_contradictory_probe: bool = False  # Points out inconsistency?
    
    # Ground truth
    human_judges_quality: List[Dict[str, Any]] = []  # How many humans thought it was good?


class VivaSession(BaseModel):
    """Full viva session simulation"""
    session_id: str
    repository_name: str
    timestamp: datetime
    
    # Questions and responses
    initial_question: str
    student_responses: List[SimulatedStudentResponse] = []
    follow_up_questions: List[VivaFollowUpQuestion] = []
    
    # Metrics
    student_level_detected: Optional[str] = None  # Did ORACLE correctly identify level?
    adapted_difficulty: bool = False  # Did questions adapt to student level?
    weakness_probing_rate: float = 0.0  # % of follow-ups that probed weaknesses
    generic_question_rate: float = 0.0  # % of follow-ups that were generic?
    
    # Overall assessment
    session_quality: float = Field(ge=0, le=1.0)
    reveals_senior_vs_junior: bool = False  # Would this distinguish engineering levels?


class SimulatedStudentResponseGenerator:
    """Generates realistic simulated student responses"""
    
    @staticmethod
    def generate_textbook_response(question: str) -> SimulatedStudentResponse:
        """Generate response that's textbook knowledge, not code-specific"""
        return SimulatedStudentResponse(
            question=question,
            response_type=StudentResponseType.TEXTBOOK,
            response_text="[Generic textbook response about computer science concepts]",
            reveals_weakness="No codebase understanding",
            confidence_expressed=0.7,
        )
    
    @staticmethod
    def generate_partial_response(question: str, missing_context: str) -> SimulatedStudentResponse:
        """Generate partially correct response missing important context"""
        return SimulatedStudentResponse(
            question=question,
            response_type=StudentResponseType.PARTIAL,
            response_text="[Correct answer but missing crucial implementation details]",
            misses_important_point=missing_context,
            confidence_expressed=0.8,
        )
    
    @staticmethod
    def generate_contradictory_response(question: str, contradiction: str) -> SimulatedStudentResponse:
        """Generate response with internal contradiction"""
        return SimulatedStudentResponse(
            question=question,
            response_type=StudentResponseType.CONTRADICTORY,
            response_text="[Statement A contradicts Statement B from earlier]",
            contains_contradiction=True,
            reveals_weakness=contradiction,
            confidence_expressed=0.6,
        )
    
    @staticmethod
    def generate_misunderstanding_response(question: str, misunderstanding: str) -> SimulatedStudentResponse:
        """Generate response based on wrong implementation assumptions"""
        return SimulatedStudentResponse(
            question=question,
            response_type=StudentResponseType.MISUNDERSTANDING,
            response_text="[Answer based on incorrect assumptions about the code]",
            assumes_wrong_context=misunderstanding,
            reveals_weakness="Fundamental misunderstanding",
            confidence_expressed=0.75,
        )
    
    @staticmethod
    def generate_weak_explanation_response(question: str, correct_answer: str) -> SimulatedStudentResponse:
        """Generate correct answer with unclear reasoning"""
        return SimulatedStudentResponse(
            question=question,
            response_type=StudentResponseType.WEAK_EXPLANATION,
            response_text=correct_answer + " [but reasoning is vague and hand-wavy]",
            reveals_weakness="Can't articulate reasoning clearly",
            confidence_expressed=0.65,
        )


class SimulatedFollowUpEvaluator:
    """Evaluates quality of ORACLE follow-up questions"""
    
    def evaluate_follow_up(
        self,
        previous_response: SimulatedStudentResponse,
        follow_up_question: str,
        oracle_confidence: float,
    ) -> VivaFollowUpQuestion:
        """Evaluate a follow-up question"""
        
        fq = VivaFollowUpQuestion(
            previous_question="",  # Would be filled from session
            follow_up_question=follow_up_question,
            oracle_confidence=oracle_confidence,
        )
        
        # Analyze follow-up quality
        if previous_response.contains_contradiction:
            if "contradict" in follow_up_question.lower() or "inconsisten" in follow_up_question.lower():
                fq.is_contradictory_probe = True
                fq.quality_assessment = FollowUpQuestionQuality.CONTRADICTING
                fq.probes_weakness = True
        
        if previous_response.reveals_weakness:
            if self._targets_weakness(follow_up_question, previous_response.reveals_weakness):
                fq.probes_weakness = True
                fq.quality_assessment = FollowUpQuestionQuality.PROBING
        
        if self._is_generic_question(follow_up_question):
            fq.is_generic = True
            fq.quality_assessment = FollowUpQuestionQuality.GENERIC
        
        if self._is_clarification(follow_up_question):
            fq.quality_assessment = FollowUpQuestionQuality.CLARIFYING
        
        if self._is_deepening(follow_up_question):
            fq.quality_assessment = FollowUpQuestionQuality.DEEPENING
        
        return fq
    
    @staticmethod
    def _targets_weakness(question: str, weakness: str) -> bool:
        """Check if question targets specific weakness"""
        weakness_keywords = weakness.lower().split()
        question_lower = question.lower()
        return any(kw in question_lower for kw in weakness_keywords if len(kw) > 3)
    
    @staticmethod
    def _is_generic_question(question: str) -> bool:
        """Check if question is generic/framework-agnostic"""
        generic_patterns = [
            "what is",
            "explain the",
            "how would you",
            "define",
            "describe the concept",
        ]
        return any(pattern in question.lower() for pattern in generic_patterns)
    
    @staticmethod
    def _is_clarification(question: str) -> bool:
        """Check if question clarifies previous answer"""
        clarification_patterns = [
            "you said",
            "when you mentioned",
            "clarify",
            "explain what you meant",
            "can you elaborate",
        ]
        return any(pattern in question.lower() for pattern in clarification_patterns)
    
    @staticmethod
    def _is_deepening(question: str) -> bool:
        """Check if question deepens understanding"""
        deepening_patterns = [
            "what if",
            "how would",
            "what happens when",
            "how does",
            "trace through",
            "walk me through",
        ]
        return any(pattern in question.lower() for pattern in deepening_patterns)


class AdaptiveVivaSimulator:
    """Simulates adaptive viva session with student responses and follow-ups"""
    
    def __init__(self):
        self.response_generator = SimulatedStudentResponseGenerator()
        self.follow_up_evaluator = SimulatedFollowUpEvaluator()
    
    def simulate_session(
        self,
        repository_name: str,
        initial_questions: List[str],
        student_level: str = "intermediate",  # junior, intermediate, senior
    ) -> List[VivaSession]:
        """Simulate full viva sessions with different student levels"""
        
        sessions = []
        
        for question in initial_questions:
            session = VivaSession(
                session_id=f"{repository_name}_{int(datetime.now().timestamp())}",
                repository_name=repository_name,
                timestamp=datetime.now(),
                initial_question=question,
            )
            
            # Generate student response based on level
            if student_level == "junior":
                response = self.response_generator.generate_partial_response(
                    question,
                    "Missing implementation details"
                )
            elif student_level == "intermediate":
                response = self.response_generator.generate_weak_explanation_response(
                    question,
                    "Somewhat correct answer"
                )
            else:  # senior
                response = SimulatedStudentResponse(
                    question=question,
                    response_type=StudentResponseType.CORRECT,
                    response_text="[Correct, detailed answer with clear reasoning]",
                    confidence_expressed=0.95,
                )
            
            session.student_responses.append(response)
            
            # Calculate metrics
            session.student_level_detected = student_level
            
            sessions.append(session)
        
        return sessions
    
    def evaluate_follow_up_set(
        self,
        sessions: List[VivaSession],
        oracle_follow_ups: Dict[str, List[str]],  # initial_q -> list of follow-ups
    ) -> Dict[str, Any]:
        """Evaluate all follow-ups across sessions"""
        
        metrics = {
            "total_follow_ups": 0,
            "probing_follow_ups": 0,
            "generic_follow_ups": 0,
            "clarifying_follow_ups": 0,
            "deepening_follow_ups": 0,
            "irrelevant_follow_ups": 0,
            
            "probing_rate": 0.0,
            "generic_rate": 0.0,
            "adaptation_quality": 0.0,
        }
        
        for session in sessions:
            for student_response in session.student_responses:
                follow_ups = oracle_follow_ups.get(student_response.question, [])
                
                for follow_up in follow_ups:
                    evaluated_fq = self.follow_up_evaluator.evaluate_follow_up(
                        student_response,
                        follow_up,
                        oracle_confidence=0.8,  # Placeholder
                    )
                    
                    session.follow_up_questions.append(evaluated_fq)
                    metrics["total_follow_ups"] += 1
                    
                    if evaluated_fq.quality_assessment == FollowUpQuestionQuality.PROBING:
                        metrics["probing_follow_ups"] += 1
                    elif evaluated_fq.quality_assessment == FollowUpQuestionQuality.GENERIC:
                        metrics["generic_follow_ups"] += 1
                    elif evaluated_fq.quality_assessment == FollowUpQuestionQuality.CLARIFYING:
                        metrics["clarifying_follow_ups"] += 1
                    elif evaluated_fq.quality_assessment == FollowUpQuestionQuality.DEEPENING:
                        metrics["deepening_follow_ups"] += 1
        
        # Calculate rates
        if metrics["total_follow_ups"] > 0:
            metrics["probing_rate"] = metrics["probing_follow_ups"] / metrics["total_follow_ups"]
            metrics["generic_rate"] = metrics["generic_follow_ups"] / metrics["total_follow_ups"]
            metrics["adaptation_quality"] = (
                metrics["probing_follow_ups"] +
                metrics["clarifying_follow_ups"] +
                metrics["deepening_follow_ups"]
            ) / metrics["total_follow_ups"]
        
        return metrics
    
    def generate_session_report(
        self,
        session: VivaSession,
    ) -> Dict[str, Any]:
        """Generate report for single session"""
        
        report = {
            "session_id": session.session_id,
            "repository": session.repository_name,
            "timestamp": session.timestamp.isoformat(),
            
            "student_responses": [],
            "follow_up_analysis": [],
            
            "metrics": {
                "total_questions": len(session.student_responses),
                "total_follow_ups": len(session.follow_up_questions),
                "probing_follow_ups": sum(
                    1 for fq in session.follow_up_questions
                    if fq.probes_weakness
                ),
                "generic_follow_ups": sum(
                    1 for fq in session.follow_up_questions
                    if fq.is_generic
                ),
            },
            
            "assessment": {
                "weakness_probing_rate": (
                    sum(1 for fq in session.follow_up_questions if fq.probes_weakness)
                    / len(session.follow_up_questions)
                    if session.follow_up_questions else 0.0
                ),
                "generic_rate": (
                    sum(1 for fq in session.follow_up_questions if fq.is_generic)
                    / len(session.follow_up_questions)
                    if session.follow_up_questions else 0.0
                ),
                "quality": session.session_quality,
            },
        }
        
        return report


